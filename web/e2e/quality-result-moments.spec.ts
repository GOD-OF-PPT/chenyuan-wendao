test('Q11 a real single harvest shows the committed item and complete cost after the motion ends without another write', async ({ page }, info) => {
    const d = driver();
    d.go('wilderness');
    await importRecoveryFixture(page, d.game);
    await runRecoveryPlan(page, { kind: 'source', sourceId: 'herbs', maxCycles: 1, until: 'cycles', target: null, monthBudget: C.sources.herbs.months, remainingMonthsReserve: 1 });
    const raw = await recoveryDatabase(page), moment = page.getByTestId('result-moment');
    await expect(moment).toBeVisible();
    await expect(moment).toContainText('取材归囊');
    await expect(moment).toContainText('凝气草 +2');
    await expect(moment).toContainText(C.sources.herbs.months + ' 游戏月');
    await page.clock.runFor(2600);
    await expect(moment).toBeVisible();
    const layout = await moment.evaluate(node => {
        const box = node.getBoundingClientRect(), copy = node.querySelector('p')!, button = node.querySelector('button')!, text = copy.getBoundingClientRect(), control = button.getBoundingClientRect();
        const luminance = (color: string) => { const rgb = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(v => { v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }); return rgb[0] * .2126 + rgb[1] * .7152 + rgb[2] * .0722; };
        const a = luminance(getComputedStyle(copy).color), b = luminance(getComputedStyle(node).backgroundColor);
        return { contrast: (Math.max(a, b) + .05) / (Math.min(a, b) + .05), textLeft: text.left, buttonLeft: control.left, buttonWidth: control.width, inside: text.top >= box.top && text.bottom <= box.bottom, font: parseFloat(getComputedStyle(copy).fontSize), belowHud: box.top >= document.querySelector('.game-hud')!.getBoundingClientRect().bottom };
    });
    expect(layout.contrast).toBeGreaterThanOrEqual(4.5);
    expect(layout.textLeft).toBeLessThan(layout.buttonLeft);
    expect(layout.buttonWidth).toBeLessThanOrEqual(110);
    expect(layout.inside).toBe(true);
    expect(layout.font).toBeGreaterThanOrEqual(18);
    expect(layout.belowHud).toBe(true);
    expect(await recoveryDatabase(page)).toEqual(raw);
    await page.screenshot({ path: info.outputPath('harvest-after-motion.png') });
});
test('Q11 quota keeps the entire original database and shows no success until the same advance is committed', async ({ page }, info) => {
    const d = driver();
    d.go('wilderness');
    const before = await importRecoveryFixture(page, d.game);
    const selected = await selectPlan(page, { kind: 'source', sourceId: 'herbs', maxCycles: 1, until: 'cycles', target: null, monthBudget: C.sources.herbs.months, remainingMonthsReserve: 1 });
    await selected.control.click();
    await expect.poll(async () => (await activitySnapshot(page))?.status).toBe('running');
    const a = await activitySnapshot(page), raw = await recoveryDatabase(page), expected = resolve(before, a.nextCommand);
    await page.evaluate(() => {
        const original = IDBObjectStore.prototype.put;
        IDBObjectStore.prototype.put = function (value: any, key?: IDBValidKey) {
            if (this.name === 'full-receipts' && value?.format === 'chenyuan-scheduled-receipt' && value.input.kind === 'ADVANCE') {
                (window as any).__q11FailedBatch = structuredClone(value);
                IDBObjectStore.prototype.put = original;
                throw new DOMException('Q11 actual batch quota', 'QuotaExceededError');
            }
            return key === undefined ? original.call(this, value) : original.call(this, value, key);
        };
    });
    await page.clock.runFor(a.cycleMs);
    await expect(page.getByTestId('save-status')).toHaveText('保存待确认');
    await expect(page.getByTestId('result-moment')).toHaveCount(0);
    expect(await recoveryDatabase(page)).toEqual(raw);
    const failed = await page.evaluate(() => (window as any).__q11FailedBatch);
    expect(failed.input.kind).toBe('ADVANCE');
    await page.screenshot({ path: info.outputPath('quota-no-result.png') });
    await page.getByTestId('retry').click();
    await expect(page.getByTestId('save-status')).toHaveText('已保存');
    await expect(page.getByTestId('result-moment')).toContainText('凝气草 +2');
    expect(await snapshot(page)).toEqual(expected.nextState);
    const committed = await recoveryDatabase(page), batches = committed.rows['full-receipts'].filter((row: any) => row.value.format === 'chenyuan-scheduled-receipt' && row.value.input.kind === 'ADVANCE');
    expect(batches).toHaveLength(1);
    expect(batches[0].value.input).toEqual(failed.input);
    expect(batches[0].value.fingerprint).toBe(failed.fingerprint);
    await page.clock.runFor(2600);
    expect(await recoveryDatabase(page)).toEqual(committed);
    await page.screenshot({ path: info.outputPath('quota-original-retry-result.png') });
});
